#!/usr/bin/env bash
# Generate .github/dependabot.yml from the stacks present in this repository.
#
#   scripts/sync-dependabot.sh          write .github/dependabot.yml
#   scripts/sync-dependabot.sh --print  print instead of writing
#
# Updates target `dev` (the integration branch), use Conventional Commit titles
# so they pass `make pr-guard` / SemVer math, and group routine bumps.

set -euo pipefail

# shellcheck source=scripts/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
cd "$(repo_root)"

OUT=".github/dependabot.yml"

entry() { # entry <ecosystem> [directory] [group-name]
  cat <<EOF
  - package-ecosystem: "$1"
    directory: "${2:-/}"
    target-branch: "dev"
    schedule:
      interval: "weekly"
    commit-message:
      prefix: "chore(deps)"
    groups:
      ${3:-all}-minor-and-patch:
        update-types: ["minor", "patch"]
EOF
}

generate() {
  local s
  printf '# Generated by scripts/sync-dependabot.sh from the detected stacks. Re-run\n'
  printf '# `make dependabot` after adding a stack; hand edits are overwritten.\n'
  printf 'version: 2\nupdates:\n'
  entry github-actions / actions
  for s in $(detect_stacks); do
    case "$s" in
      python) if [ -f pyproject.toml ]; then entry uv / python; else entry pip / python; fi ;;
      node)   if [ "$(node_pm)" = bun ]; then entry bun / npm; else entry npm / npm; fi ;;
      rust)   entry cargo / cargo ;;
      swift)  entry swift / swift ;;
    esac
  done
  if [ -f Dockerfile ]; then entry docker / docker; fi
  if [ -d .devcontainer ]; then entry devcontainers / devcontainers; fi
}

if [ "${1:-}" = "--print" ]; then generate
else
  mkdir -p "$(dirname "$OUT")"
  generate > "$OUT"
  ok "wrote $OUT for: $(detect_stacks | tr '\n' ' ')github-actions"
fi
