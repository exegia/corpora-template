#!/usr/bin/env bash
# Build CHANGELOG.md sections from Conventional Commit subjects.
#
#   scripts/changelog.sh section VERSION [TO]   print a section for latest-tag..TO (default origin/next)
#   scripts/changelog.sh update  VERSION [TO]   insert or replace that section in CHANGELOG.md
#   scripts/changelog.sh extract VERSION        print the body of VERSION's section (release notes)
#
# `update` is idempotent: re-running it for the same VERSION replaces the section,
# which is what a refreshed release branch needs.

set -euo pipefail

# shellcheck source=scripts/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
cd "$(repo_root)"

CHANGELOG="${CHANGELOG:-CHANGELOG.md}"

HEADER='# Changelog

All notable changes to this project are documented here. The format follows
[Keep a Changelog](https://keepachangelog.com/en/1.1.0/) and the project adheres to
[Semantic Versioning](https://semver.org/spec/v2.0.0.html).

Sections are generated by `scripts/changelog.sh` when a release branch is cut.
'

# Strip "type(scope)!: " into "**scope:** " / "".
pretty() { sed -E 's/^[a-z]+\(([^)]+)\)!?: (.*)$/**\1:** \2/; s/^[a-z]+!?: //'; }

group() { # group <title> <subjects> <extended-regex>
  local lines
  lines="$(printf '%s\n' "$2" | grep -E "$3" | pretty | sed 's/^/- /' || true)"
  [ -n "$lines" ] || return 0
  printf '### %s\n\n%s\n\n' "$1" "$lines"
}

cmd_section() {
  local ver="${1:-}" to="${2:-origin/next}" range subjects bodies known notes
  is_semver "$ver" || die "usage: changelog.sh section X.Y.Z [TO]"
  git rev-parse --verify --quiet "$to^{commit}" >/dev/null || die "unknown revision: $to"
  range="$(unreleased_range "$to")"
  subjects="$(git log --no-merges --reverse --format=%s "$range")"
  bodies="$(git log --no-merges --format=%b "$range")"

  printf '## [%s] - %s\n\n' "$ver" "$(date -u +%F)"
  if [ -z "$subjects" ]; then printf '_No notable changes._\n\n'; return 0; fi

  known='^(feat|fix|perf|refactor|docs|build|ci|ai|test|chore|style|revert)(\([^)]*\))?!?: '
  if printf '%s\n' "$bodies" | grep -Eq '^BREAKING[ -]CHANGE(:| )' \
     || printf '%s\n' "$subjects" | grep -Eq '^[a-z]+(\([^)]*\))?!:'; then
    group 'Breaking changes' "$subjects" '^[a-z]+(\([^)]*\))?!:'
    notes="$(printf '%s\n' "$bodies" | grep -E '^BREAKING[ -]CHANGE(:| )' | sed -E 's/^BREAKING[ -]CHANGE:? ?/- /' || true)"
    [ -z "$notes" ] || printf '### Breaking change notes\n\n%s\n\n' "$notes"
  fi
  group 'Features'            "$subjects" '^feat(\([^)]*\))?!?: '
  group 'Bug fixes'           "$subjects" '^fix(\([^)]*\))?!?: '
  group 'Performance'         "$subjects" '^perf(\([^)]*\))?!?: '
  group 'Refactoring'         "$subjects" '^refactor(\([^)]*\))?!?: '
  group 'AI and agents'       "$subjects" '^ai(\([^)]*\))?!?: '
  group 'Documentation'       "$subjects" '^docs(\([^)]*\))?!?: '
  group 'Build and CI'        "$subjects" '^(build|ci)(\([^)]*\))?!?: '
  group 'Maintenance'         "$subjects" '^(test|chore|style|revert)(\([^)]*\))?!?: '
  local other
  other="$(printf '%s\n' "$subjects" | grep -Ev "$known" | sed 's/^/- /' || true)"
  [ -z "$other" ] || printf '### Other changes\n\n%s\n\n' "$other"
}

cmd_update() {
  local ver="${1:-}" to="${2:-origin/next}" sec tmp
  sec="$(mktemp)"; tmp="$(mktemp)"
  cmd_section "$ver" "$to" > "$sec"
  [ -f "$CHANGELOG" ] || printf '%s\n' "$HEADER" > "$CHANGELOG"

  awk -v ver="$ver" -v secfile="$sec" '
    function dump(   l) { while ((getline l < secfile) > 0) print l; close(secfile); done = 1 }
    /^## \[/ {
      skipping = 0
      if (index($0, "## [" ver "]") == 1) { skipping = 1; if (!done) dump(); next }
      if (!done) dump()
    }
    skipping { next }
    { print }
    END { if (!done) dump() }
  ' "$CHANGELOG" > "$tmp"
  cat "$tmp" > "$CHANGELOG"
  rm -f "$sec" "$tmp"
  ok "$CHANGELOG has a section for $ver"
}

cmd_extract() {
  local ver="${1:-}"
  is_semver "$ver" || die "usage: changelog.sh extract X.Y.Z"
  [ -f "$CHANGELOG" ] || return 0
  awk -v ver="$ver" '
    /^## \[/ { on = (index($0, "## [" ver "]") == 1); next }
    on { print }
  ' "$CHANGELOG" | awk '
    { l[NR] = $0 }
    END {
      s = 1; while (s <= NR && l[s] ~ /^[[:space:]]*$/) s++
      e = NR; while (e >= s && l[e] ~ /^[[:space:]]*$/) e--
      for (i = s; i <= e; i++) print l[i]
    }'
}

main() {
  local cmd="${1:-}"; [ "$#" -gt 0 ] && shift
  case "$cmd" in
    section) cmd_section "$@" ;;
    update)  cmd_update "$@" ;;
    extract) cmd_extract "$@" ;;
    *) sed -n '2,10p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; [ -z "$cmd" ] || exit 2 ;;
  esac
}

main "$@"
